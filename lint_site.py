class PageParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.hrefs: list[str] = []
        self.ids: set[str] = set()
        self.canonical: list[str] = []
        self.alternates: dict[str, list[str]] = {}
        self.i18n_keys: set[str] = set()
        self.html_lang = ""
        self.html_data_pages: list[str] = []
        self.html_count = 0
        self.h1_count = 0
        self.has_viewport = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        values = {key: value or "" for key, value in attrs}
        if tag == "html":
            self.html_count += 1
            self.html_lang = values.get("lang", "")
            self.html_data_pages.extend(
                value or ""
                for key, value in attrs
                if key == "data-page"
            )
        if tag == "meta" and values.get("name", "").casefold() == "viewport":
            self.has_viewport = bool(values.get("content"))
        if tag == "a" and values.get("href"):
            self.hrefs.append(values["href"])
        if tag == "script" and values.get("src"):
            self.hrefs.append(values["src"])
        if values.get("id"):
            self.ids.add(values["id"])
        if values.get("data-i18n"):
            self.i18n_keys.add(values["data-i18n"])
        if values.get("data-i18n-content"):
            self.i18n_keys.add(values["data-i18n-content"])
        if tag == "link" and values.get("href"):
            relation = values.get("rel", "").casefold()
            if relation == "canonical":
                self.canonical.append(values["href"])
            elif relation == "alternate" and values.get("hreflang"):
                self.alternates.setdefault(values["hreflang"], []).append(
                    values["href"]
                )
            else:
                self.hrefs.append(values["href"])
        if tag == "h1":
            self.h1_count += 1


