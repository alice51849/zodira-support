def lint_root_navs(locales: dict[str, dict[str, str]]) -> list[str]:
    errors: list[str] = []
    for name, contract in ROOT_NAV_CONTRACTS.items():
        parser = ContainerAnchorParser("nav", "nav")
        parser.feed((ROOT / name).read_text(encoding="utf-8"))
        parser.close()
        if len(parser.anchors) != len(contract):
            errors.append(f"{name}: root nav must contain exactly support and privacy")
            continue

        destinations: list[str] = []
        for anchor, (href, key, current) in zip(parser.anchors, contract):
            destinations.append(anchor.get("href", ""))
            if anchor.get("href") != href or anchor.get("data-i18n") != key:
                errors.append(f"{name}: root nav destination contract mismatch")
            if (anchor.get("aria-current") == "page") != current:
                errors.append(f"{name}: root nav current-page state mismatch")
            if "data-surface" in anchor or "data-localized-link" in anchor:
                errors.append(f"{name}: root nav must stay static and unambiguous")
        if len(destinations) != len(set(destinations)):
            errors.append(f"{name}: root nav has duplicate destinations")

        for locale, copy in locales.items():
            labels = [
                " ".join(copy[key].split()).casefold()
                for _, key, _ in contract
            ]
            if len(labels) != len(set(labels)):
                errors.append(f"{name}: duplicate visible nav label in {locale}")
    return errors


def site_anchor_target(current: str, href: str) -> str | None:
    if not href or href.startswith(("#", "mailto:", "tel:")):
        return None
    parsed = urlsplit(href)
    site = urlsplit(SITE_ROOT)
    if parsed.scheme in {"http", "https"}:
        if parsed.scheme != site.scheme or parsed.netloc != site.netloc:
            return None
        if not parsed.path.startswith(site.path):
            return None
        relative = unquote(parsed.path[len(site.path):])
    elif parsed.scheme or parsed.netloc:
        return None
    else:
        relative = (Path(current).parent / unquote(parsed.path)).as_posix()

    target = (ROOT / relative).resolve()
    if not target.suffix:
        target /= "index.html"
    if target != ROOT and ROOT not in target.parents:
        return None
    return target.relative_to(ROOT).as_posix()


def lint_root_static_graph(locales: dict[str, dict[str, str]]) -> list[str]:
    errors: list[str] = []
    required = {
        f"{locale}/{surface}"
        for locale in OFFICIAL_LOCALES
        for surface in STATIC_SURFACES
    }
    for name, (expected_href, expected_label) in ROOT_STATIC_ENTRIES.items():
        source = (ROOT / name).read_text(encoding="utf-8")
        parser = ContainerAnchorParser("div", "footer-links")
        parser.feed(source)
        parser.close()
        rendered_labels = []
        for anchor in parser.anchors:
            key = anchor.get("data-i18n")
            label = locales["en-US"].get(key, "") if key else anchor.get("text", "")
            rendered_labels.append(" ".join(label.split()).casefold())
        if len(rendered_labels) != len(set(rendered_labels)):
            errors.append(f"{name}: footer links have duplicate visible labels")

        static_anchors = [
            anchor for anchor in parser.anchors
            if site_anchor_target(name, anchor.get("href", "")) in required
        ]
        if [(anchor.get("href"), anchor.get("text")) for anchor in static_anchors] != [
            (expected_href, expected_label)
        ]:
            errors.append(f"{name}: static footer entry contract mismatch")
        expected_marker = (
            f'<!-- root-static-entry:start --><a href="{expected_href}">'
            f'{expected_label}</a><!-- root-static-entry:end -->'
        )
        if source.count(expected_marker) != 1:
            errors.append(f"{name}: generated static footer entry is stale")

    nodes = required | set(ROOT_STATIC_ENTRIES)
    reached = set(ROOT_STATIC_ENTRIES)
    pending = list(reached)
    while pending:
        current = pending.pop()
        path = ROOT / current
        if not path.is_file():
            continue
        parser = AnchorHrefParser()
        parser.feed(path.read_text(encoding="utf-8"))
        parser.close()
        for href in parser.hrefs:
            target = site_anchor_target(current, href)
            if target in nodes and target not in reached:
                reached.add(target)
                pending.append(target)

    unreachable = sorted(required - reached)
    if unreachable:
        errors.append(
            f"root anchor graph reaches {len(required) - len(unreachable)}/"
            f"{len(required)} required surfaces; missing={unreachable[:10]}"
        )
    return errors


def lint_static_surfaces() -> list[str]:
    errors: list[str] = []
    canonical_owners: dict[str, list[str]] = {}
    for locale in OFFICIAL_LOCALES:
        for name in STATIC_SURFACES:
            relative = f"{locale}/{name}"
            path = ROOT / relative
            if not path.is_file():
                errors.append(f"{relative}: missing static surface")
                continue
            parser = PageParser()
            parser.feed(path.read_text(encoding="utf-8"))
            parser.close()
            expected = f"{SITE_ROOT}{relative}"
            if parser.canonical != [expected]:
                errors.append(f"{relative}: static canonical mismatch")
            else:
                canonical_owners.setdefault(expected, []).append(relative)
            expected_default = f"{SITE_ROOT}en-US/{name}"
            if parser.alternates.get("x-default") != [expected_default]:
                errors.append(f"{relative}: static x-default mismatch")

    expected_count = len(OFFICIAL_LOCALES) * len(STATIC_SURFACES)
    if len(canonical_owners) != expected_count:
        errors.append("static surfaces: canonical targets are not unique")
    for canonical, owners in canonical_owners.items():
        if len(owners) != 1:
            errors.append(f"static surfaces: canonical {canonical} owned by {owners}")
    return errors


def frozen_js_map(source: str, name: str) -> dict[str, str]:
    match = re.search(
        rf"const\s+{re.escape(name)}\s*=\s*Object\.freeze\((\{{.*?\}})\);",
        source,
        re.S,
    )
    if not match:
        return {}
    try:
        value = json.loads(match.group(1))
    except json.JSONDecodeError:
        return {}
    return value if isinstance(value, dict) else {}


def lint_legacy_router() -> list[str]:
    errors: list[str] = []
    source = (ROOT / "localize.js").read_text(encoding="utf-8")
    route_map = frozen_js_map(source, "STATIC_LOCALE_ROUTES")
    expected_routes = {locale: locale for locale in OFFICIAL_LOCALES}
    if list(route_map) != list(OFFICIAL_LOCALES) or route_map != expected_routes:
        errors.append("localize.js: static locale route map is not fixed exact-50")
    if frozen_js_map(source, "STATIC_SURFACES") != {
        "index": "support.html",
        "privacy": "privacy.html",
    }:
        errors.append("localize.js: legacy root surface map mismatch")
    for contract in (
        'preserved.delete("lang")',
        "next.hash = window.location.hash",
        "window.location.replace(target.href)",
    ):
        if contract not in source:
            errors.append(f"localize.js: missing legacy route contract {contract!r}")
    return errors


def lint_identity_and_contact() -> list[str]:
    errors: list[str] = []
    site_files = (
        "index.html", "privacy.html", "terms.html", "robots.txt", "sitemap.xml",
        "styles.css", "locales.js", "localize.js",
    )
    current_metadata_files = [
        CANONICAL_METADATA,
        *FASTLANE_METADATA.glob("*/*.txt"),
        URL_BUILDER,
    ]
    public_sources = [(ROOT / name) for name in site_files] + current_metadata_files
    url_mirrors = list(FASTLANE_METADATA.glob("*/*_url.txt"))
    if BACKUP_METADATA.is_dir():
        url_mirrors.extend(BACKUP_METADATA.glob("*/*_url.txt"))

    for path in public_sources + url_mirrors:
        source = path.read_text(encoding="utf-8")
        folded = source.casefold()
        for token in LEGACY_TOKENS:
            if token in folded:
                errors.append(f"{path}: stale public identity token {token!r}")
        if re.search(r"\b" + "Astrea" + r"\b", source.replace(BUNDLE_ID, "")):
            errors.append(f"{path}: stale public Astrea brand")
        for email in EMAIL_RE.findall(source):
            if email.casefold() != ALLOWED_EMAIL:
                errors.append(f"{path}: disallowed public email {email}")

    site_source = "\n".join(
        (ROOT / name).read_text(encoding="utf-8") for name in site_files
    )
    if site_source.count(BUNDLE_ID) != 1:
        errors.append("privacy bundle ID must appear exactly once on the public site")
    without_bundle = site_source.replace(BUNDLE_ID, "")
    if re.search(r"\b" + "Astrea" + r"\b", without_bundle):
        errors.append("public site contains stale Astrea branding outside the legal bundle ID")
    if BUNDLE_ID not in (ROOT / "privacy.html").read_text(encoding="utf-8"):
        errors.append("privacy.html: missing the registered bundle ID")

    campaigns = re.findall(r"utm_campaign=([^&\"']+)", site_source)
    if not campaigns:
        errors.append("site: missing support-site campaign")
    elif any(campaign != "sup_zodira" for campaign in campaigns):
        errors.append(f"site: campaign mismatch {campaigns}")
    return errors


def lint_metadata_urls(
    locales: dict[str, dict[str, str]],
) -> list[str]:
    errors: list[str] = []
    canonical = json.loads(CANONICAL_METADATA.read_text(encoding="utf-8"))
    if tuple(canonical.get("_meta", {}).get("localeOrder", ())) != OFFICIAL_LOCALES:
        errors.append("canonical metadata localeOrder is not the official exact-50 order")
    if set(canonical) - {"_meta"} != LOCALE_SET:
        errors.append("canonical metadata locale records are not exact-50")

    actual_dirs = {path.name for path in FASTLANE_METADATA.iterdir() if path.is_dir()}
    if actual_dirs != LOCALE_SET:
        errors.append(
            "fastlane metadata locale mismatch "
            f"missing={sorted(LOCALE_SET - actual_dirs)} "
            f"extra={sorted(actual_dirs - LOCALE_SET)}"
        )
    for locale in OFFICIAL_LOCALES:
        expected = {
            "supportUrl": expected_support_url(locale),
            "privacyPolicyUrl": expected_privacy_url(locale),
        }
        record = canonical.get(locale, {})
        for field, value in expected.items():
            if record.get(field) != value:
                errors.append(f"canonical {locale}/{field} must be {value}")
        if locale in locales:
            if locales[locale].get("description") != record.get("description"):
                errors.append(f"locales.js: {locale}/description differs from canonical")
            if locales[locale].get("workflow") != record.get("whatsNew"):
                errors.append(f"locales.js: {locale}/workflow differs from canonical")

        files = {
            "support_url.txt": expected_support_url(locale),
            "privacy_url.txt": expected_privacy_url(locale),
            "marketing_url.txt": expected_support_url(locale),
        }
        for filename, value in files.items():
            path = FASTLANE_METADATA / locale / filename
            actual = path.read_text(encoding="utf-8") if path.is_file() else ""
            if actual != value:
                errors.append(f"{path}: expected {value!r}, found {actual!r}")
            parsed = urlsplit(actual)
            query = parse_qs(parsed.query, strict_parsing=True) if actual else {}
            if query != {"lang": [locale]}:
                errors.append(f"{path}: locale query must be exactly lang={locale}")

    if BACKUP_METADATA.is_dir():
        for path in BACKUP_METADATA.glob("*/*_url.txt"):
            locale = path.parent.name
            if locale not in LOCALE_SET:
                errors.append(f"{path}: unexpected backup locale")
                continue
            expected = (
                expected_privacy_url(locale)
                if path.name == "privacy_url.txt"
                else expected_support_url(locale)
            )
            if path.read_text(encoding="utf-8") != expected:
                errors.append(f"{path}: stale direct URL mirror")
    return errors


def lint_sitemap_and_robots() -> list[str]:
    errors: list[str] = []
    source = (ROOT / "sitemap.xml").read_text(encoding="utf-8")
    urls = re.findall(r"<loc>([^<]+)</loc>", source)
    expected = [
        *PAGES.values(),
        *(
            f"{SITE_ROOT}{locale}/{name}"
            for locale in OFFICIAL_LOCALES
            for name in STATIC_SURFACES
        ),
    ]
    if any(urlsplit(url).query or urlsplit(url).fragment for url in urls):
        errors.append("sitemap.xml: query strings and fragments are forbidden")
    if len(urls) != len(set(urls)):
        errors.append("sitemap.xml: duplicate URL")
    if urls != expected:
        url_set = set(urls)
        expected_set = set(expected)
        errors.append(
            "sitemap.xml: URL mismatch "
            f"missing={sorted(expected_set - url_set)} "
            f"extra={sorted(url_set - expected_set)}"
        )
    robots = (ROOT / "robots.txt").read_text(encoding="utf-8")
    expected_line = f"Sitemap: {SITE_ROOT}sitemap.xml"
    if expected_line not in robots:
        errors.append(f"robots.txt: missing {expected_line}")
    return errors


def main() -> None:
    locales, errors = parse_locales()
    locale_keys = set(next(iter(locales.values()), {}))
    for name, canonical in PAGES.items():
        errors.extend(lint_page(name, canonical, locale_keys))
    errors.extend(lint_root_navs(locales))
    errors.extend(lint_root_static_graph(locales))
    errors.extend(lint_static_surfaces())
    errors.extend(lint_identity_and_contact())
    errors.extend(lint_metadata_urls(locales))
    errors.extend(lint_sitemap_and_robots())
    errors.extend(lint_legacy_router())

    loader = (ROOT / "localize.js").read_text(encoding="utf-8")
    for contract in (
        "URLSearchParams", "STATIC_LOCALE_ROUTES",
        "document.documentElement.dir", "Object.hasOwn(STATIC_LOCALE_ROUTES, requested)",
    ):
        if contract not in loader:
            errors.append(f"localize.js: missing fail-closed locale contract {contract!r}")

    if errors:
        print("\n".join(errors), file=sys.stderr)
        raise SystemExit(1)
    print(
        "site lint passed: canonical identity, exact-50 native dictionary, "
        "localized URLs, mirrors, sitemap, contact and legal bundle exception"
    )


if __name__ == "__main__":
    main()
